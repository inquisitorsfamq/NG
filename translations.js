let isTranslating = false;

/**
 * Universal text node translator using bidirectional phrase replacement
 */
function translateDOM(targetLang) {
  if (isTranslating) return;
  isTranslating = true;

  try {
    const phraseList = targetLang === 'ru' ? PHRASES_UK_TO_RU : PHRASES_RU_TO_UK;
    const fromIdx = targetLang === 'ru' ? 0 : 1;
    const toIdx = targetLang === 'ru' ? 1 : 0;

    function translateString(str) {
      if (!str || typeof str !== 'string') return str;
      let trimmed = str.trim();
      if (!trimmed) return str;

      // Exact match first
      for (let i = 0; i < phraseList.length; i++) {
        const pair = phraseList[i];
        if (trimmed === pair[fromIdx]) {
          return str.replace(pair[fromIdx], pair[toIdx]);
        }
      }

      // Partial / multi-phrase replacement
      let result = str;
      for (let i = 0; i < phraseList.length; i++) {
        const pair = phraseList[i];
        if (result.includes(pair[fromIdx])) {
          result = result.split(pair[fromIdx]).join(pair[toIdx]);
        }
      }
      return result;
    }

    // 1. Walk DOM text nodes
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode(node) {
          if (!node || !node.parentNode) return NodeFilter.FILTER_REJECT;
          const tagName = node.parentNode.tagName;
          if (['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE'].includes(tagName)) {
            return NodeFilter.FILTER_REJECT;
          }
          if (node.parentNode.closest && node.parentNode.closest('.no-translate')) {
            return NodeFilter.FILTER_REJECT;
          }
          const val = node.nodeValue;
          if (!val || !val.trim() || /^\d+$/.test(val.trim())) {
            return NodeFilter.FILTER_SKIP;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const nodesToUpdate = [];
    let currentNode = walker.nextNode();
    while (currentNode) {
      nodesToUpdate.push(currentNode);
      currentNode = walker.nextNode();
    }

    nodesToUpdate.forEach(node => {
      if (!node._origTextUk) {
        node._origTextUk = node.nodeValue;
      }
      if (targetLang === 'uk') {
        if (node._origTextUk) {
          node.nodeValue = node._origTextUk;
        } else {
          node.nodeValue = translateString(node.nodeValue);
        }
      } else {
        const sourceText = node._origTextUk || node.nodeValue;
        node.nodeValue = translateString(sourceText);
      }
    });

    // 2. Attributes (placeholder, title, aria-label)
    document.querySelectorAll('input, textarea').forEach(input => {
      if (input.placeholder) {
        if (!input._origPlaceholderUk) input._origPlaceholderUk = input.placeholder;
        if (targetLang === 'uk') {
          input.placeholder = input._origPlaceholderUk;
        } else {
          input.placeholder = translateString(input._origPlaceholderUk || input.placeholder);
        }
      }
    });

    document.querySelectorAll('[title]').forEach(el => {
      if (el.title) {
        if (!el._origTitleUk) el._origTitleUk = el.title;
        if (targetLang === 'uk') {
          el.title = el._origTitleUk;
        } else {
          el.title = translateString(el._origTitleUk || el.title);
        }
      }
    });

    document.querySelectorAll('option').forEach(opt => {
      if (opt.textContent) {
        if (!opt._origTextUk) opt._origTextUk = opt.textContent;
        if (targetLang === 'uk') {
          opt.textContent = opt._origTextUk;
        } else {
          opt.textContent = translateString(opt._origTextUk || opt.textContent);
        }
      }
    });

    // 3. Elements with data-i18n attributes
    const dict = translations[targetLang] || translations.uk;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // 4. Update Document Title
    if (targetLang === 'ru') {
      if (document.title.includes("Офіційний сайт")) {
        document.title = document.title.replace("Офіційний сайт", "Официальный сайт");
      }
      if (document.title.includes("Офіційний портал")) {
        document.title = document.title.replace("Офіційний портал", "Официальный портал");
      }
      if (document.title.includes("Офіційний Мерч")) {
        document.title = document.title.replace("Офіційний Мерч", "Официальный Мерч");
      }
      if (document.title.includes("сім'ї")) {
        document.title = document.title.replace("сім'ї", "семьи");
      }
    } else {
      if (document.title.includes("Официальный сайт")) {
        document.title = document.title.replace("Официальный сайт", "Офіційний сайт");
      }
      if (document.title.includes("Официальный портал")) {
        document.title = document.title.replace("Официальный портал", "Офіційний портал");
      }
      if (document.title.includes("Официальный Мерч")) {
        document.title = document.title.replace("Официальный Мерч", "Офіційний Мерч");
      }
      if (document.title.includes("семьи")) {
        document.title = document.title.replace("семьи", "сім'ї");
      }
    }
  } catch (err) {
    console.error('Translation error:', err);
  } finally {
    isTranslating = false;
  }
}

/**
 * Public setLanguage API
 */
function setLanguage(lang, notify = true) {
  if (lang !== 'uk' && lang !== 'ru') lang = 'uk';
  currentLang = lang;

  try {
    localStorage.setItem('inq_famq_lang', lang);
  } catch (e) {}

  document.documentElement.lang = lang;

  // Update navbar & mobile buttons state
  document.querySelectorAll('.lang-btn-uk').forEach(btn => {
    if (lang === 'uk') {
      btn.className = 'lang-btn-uk px-2.5 py-1 rounded-lg text-[11px] font-black bg-tiffany text-darkbg-950 shadow-sm transition-all';
    } else {
      btn.className = 'lang-btn-uk px-2.5 py-1 rounded-lg text-[11px] font-bold text-slate-400 hover:text-white transition-all';
    }
  });

  document.querySelectorAll('.lang-btn-ru').forEach(btn => {
    if (lang === 'ru') {
      btn.className = 'lang-btn-ru px-2.5 py-1 rounded-lg text-[11px] font-black bg-tiffany text-darkbg-950 shadow-sm transition-all';
    } else {
      btn.className = 'lang-btn-ru px-2.5 py-1 rounded-lg text-[11px] font-bold text-slate-400 hover:text-white transition-all';
    }
  });

  // Re-render merch catalog if on merch.html BEFORE translating DOM
  if (typeof renderCatalog === 'function') {
    try { renderCatalog(); } catch (e) {}
  }

  // Execute full-page translation
  translateDOM(lang);

  // Audio click feedback
  if (typeof playSfx === 'function') {
    try { playSfx('click'); } catch (e) {}
  }

  // Toast feedback
  const toastMsg = lang === 'ru'
    ? "🇷🇺 Язык сайта переключен на русский!"
    : "🇺🇦 Мову сайту перемкнено на українську!";

  if (notify && typeof showToast === 'function') {
    showToast(toastMsg);
  } else if (notify && typeof showMerchToast === 'function') {
    showMerchToast(toastMsg);
  }

  // Dispatch custom event for dynamic components
  try {
    window.dispatchEvent(new CustomEvent('inqLanguageChanged', { detail: { lang } }));
  } catch (e) {}
}

/**
 * Initialize on page load
 */
function initLanguage() {
  let saved = 'uk';
  try {
    saved = localStorage.getItem('inq_famq_lang') || 'uk';
  } catch (e) {
    saved = 'uk';
  }

  currentLang = 'uk'; // Baseline HTML is in Ukrainian
  if (saved === 'ru') {
    setLanguage('ru', false);
  } else {
    setLanguage('uk', false);
  }
}

// Auto-run on DOM ready
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguage);
  } else {
    initLanguage();
  }
}
